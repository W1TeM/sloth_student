# --- Задание 1 (Уровень pH) ---
print("--- Задание 1 ---")
ph = float(input("Введите значение pH: "))
if ph < 7:
    print("Кислая среда")
elif ph == 7:
    print("Нейтральная среда")
else:
    print("Щелочная среда")
print()

# --- Задание 2 (Температурные диапазоны, код из примера) ---
print("--- Задание 2 (Температура) ---")
temp = float(input("Какая температура листа сейчас? "))
if temp < 5:
    print("Слишком холодно. Фотосинтез почти не идёт.")
elif 5 <= temp <= 25:
    print("Оптимально для растений с С3-метаболизмом")
elif 25 < temp <= 35:
    print("Хорошо для растений С4-метаболизмом")
else:
    print("It's hot as hell! Cool down, bro.")
print()

# --- Задание 3 (Переливание крови) ---
print("--- Задание 3 (Переливание крови) ---")
donor_type = input("Введите группу крови донора (I, II, III, IV): ").strip().upper()
recipient_type = input("Введите группу крови пациента (I, II, III, IV): ").strip().upper()

# Переливание возможно, если группы совпадают ИЛИ донор имеет I (нулевую) группу
if donor_type == recipient_type or donor_type == "I":
    print("Рекомендация: Переливание ВОЗМОЖНО.")
else:
    print("Рекомендация: Переливание НЕВОЗМОЖНО. Риск для пациента.")
print()

# --- Итоговое задание (Богатырь на распутье) ---
print("--- Задание 4 (Богатырь на распутье) ---")
print("Подъехал богатырь к камню, а там надпись:")
print("Прямо, направо или налево?")
choice = input("Ваш выбор: ").strip().lower()

if choice == "прямо" or choice == "поехать прямо":
    print("Прямо ехати — живу не бывати: нет пути ни проезжему, ни прохожему, ни пролетному!")
elif choice == "направо" or choice == "поехать направо":
    print("Направо ехати — женату быти!")
elif choice == "налево" or choice == "поехать налево":
    print("Налево ехати — богату быти!")
else:
    print("Богатырь задумался, да так и остался стоять у камня.")
print()